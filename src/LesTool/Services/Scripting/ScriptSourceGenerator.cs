using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace LesTool.Services.Scripting;

/// <summary>
/// 把 .csx 正文包装成可由 CSharpCompilation 编译的普通源码：文件头 using 提升到包装
/// 单元顶部，顶层类型声明提升为包装类的嵌套类型，其余语句全部进入 __Run 方法体。
/// 原文件的每一行（含被提升而空出的行）都按原行号重排，配合 #line 重映射，
/// 编译诊断与运行时异常堆栈都指向 .csx 的真实行号。
/// 入口方法参数名刻意叫 Les——脚本里 Les.Xxx 的写法与旧脚本引擎完全一致。
/// </summary>
public static class ScriptSourceGenerator
{
    /// <summary>默认 using（与旧脚本引擎 AddImports 同口径）；用户已写同名指令则不再补。</summary>
    private static readonly string[] DefaultUsings =
    {
        "System", "System.IO", "System.Linq", "System.Text",
        "System.Diagnostics", "System.Windows", "LesTool", "LesTool.Services",
    };

    public static string Generate(string scriptPath, string scriptCode)
    {
        var text = scriptCode.StartsWith('\uFEFF') ? scriptCode[1..] : scriptCode; // 去 BOM 字符
        var lines = text.Replace("\r\n", "\n").Replace("\r", "\n").Split('\n');

        var root = (CompilationUnitSyntax)CSharpSyntaxTree.ParseText(text).GetRoot();

        // ① 提升 using：Roslyn 给出权威清单（正确处理 using static / 别名 / 同行多条）
        var hoistedUsings = new List<string>();
        var blankedLines = new HashSet<int>();
        foreach (var directive in root.Usings)
        {
            hoistedUsings.Add(directive.ToString().Trim());
            BlankSpanLines(directive, lines.Length, blankedLines);
        }

        // ② 提升顶层类型声明（class/struct/enum/delegate/interface）为 __Script 嵌套类型；
        //    方法体语句留在原地。用语法树区分，正则做不可靠。
        var hoistedMembers = new List<string>();
        foreach (var member in root.Members)
        {
            if (member is GlobalStatementSyntax) continue;
            var span = member.GetLocation().GetLineSpan();
            var start = span.StartLinePosition.Line;
            var end = Math.Min(span.EndLinePosition.Line, lines.Length - 1);
            var sb = new StringBuilder();
            // 声明被挪离原位，靠 #line 把诊断与堆栈拉回 .csx 原行号
            sb.Append("#line ").Append(start + 1).Append(" \"").Append(scriptPath).Append('"').AppendLine();
            for (var i = start; i <= end; i++)
                sb.AppendLine(lines[i]);
            hoistedMembers.Add(sb.ToString());
            for (var i = start; i <= end; i++)
                blankedLines.Add(i);
        }

        // ③ 组装。正文按行号原样重排（提升处留空行），行首统一 #line 1 映射。
        var output = new StringBuilder(text.Length + 1024);
        output.AppendLine("// <auto-generated> LesTool 用户脚本包装 — 引擎 v1，勿手改。");
        output.AppendLine("#pragma warning disable CS1998");
        foreach (var ns in DefaultUsings)
            if (!hoistedUsings.Contains($"using {ns};"))
                output.Append("using ").Append(ns).Append(';').AppendLine();
        foreach (var usingDirective in hoistedUsings)
            output.AppendLine(usingDirective);
        output.AppendLine();
        output.AppendLine("namespace LesTool.ScriptHost;");
        output.AppendLine();
        output.AppendLine("public static class __Script");
        output.AppendLine("{");
        foreach (var member in hoistedMembers)
            output.AppendLine(member);
        output.AppendLine("    public static async System.Threading.Tasks.Task __Run(LesTool.Services.Scripting.LesApi Les)");
        output.AppendLine("    {");
        output.Append("        #line 1 \"").Append(scriptPath).AppendLine("\"");
        for (var i = 0; i < lines.Length; i++)
            output.Append("        ").AppendLine(blankedLines.Contains(i) ? "" : lines[i]);
        output.AppendLine("    }");
        output.AppendLine("}");
        return output.ToString();
    }

    /// <summary>把节点覆盖的行标记为“已提升”，正文里这些行留空占位、行号不变。</summary>
    private static void BlankSpanLines(SyntaxNode node, int lineCount, HashSet<int> blanked)
    {
        var span = node.GetLocation().GetLineSpan();
        for (var i = span.StartLinePosition.Line; i <= Math.Min(span.EndLinePosition.Line, lineCount - 1); i++)
            blanked.Add(i);
    }
}
